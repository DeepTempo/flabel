#: because correlation joins it against Zeek's epoch ``ts`` (spec §9).
HTTP_ALERT_TS = 1700000000.05

SEMVER = re.compile(r"\d+\.\d+\.\d+")


# --- fixture generators -------------------------------------------------------------------


def _load_canary() -> object:
    """Load ``make_canary.py`` as a module for its packet-building helpers.

    Imported rather than re-implemented: its IP/TCP checksum code is already verified
    against Zeek and Suricata, and a capture with a wrong checksum is exactly the kind of
    fixture that fails in a way no assertion explains. It is a fixture generator, not
    library code, hence the explicit file load.
    """
    spec = importlib.util.spec_from_file_location("flabel_make_canary", FIXTURES / "make_canary.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


CANARY = _load_canary()

TLS_CLIENT = "10.0.0.7"
TLS_SERVER = "10.0.0.202"
TLS_SPORT = 49200
TLS_BASE_TS = 1700000100.0


def _extension(kind: int, body: bytes) -> bytes:
    return struct.pack("!HH", kind, len(body)) + body


def _client_hello() -> bytes:
    """A TLS 1.3 ClientHello whose JA4_a segment is ``t13d0405h2``.

    Fixed content — including the 32 "random" bytes — so the JA4 value is identical on every
    run: TCP, TLS 1.3 (from ``supported_versions``), SNI present, 4 ciphers, 5 extensions,
    first ALPN ``h2``. That is what ``synthetic.rules`` sid 9000002 matches on.
    """
    host = b"flabel.test"
    server_name = _extension(0x0000, struct.pack("!HBH", len(host) + 3, 0, len(host)) + host)
    supported_groups = _extension(0x000A, struct.pack("!HH", 2, 0x001D))
    signature_algorithms = _extension(0x000D, struct.pack("!HHHH", 6, 0x0403, 0x0804, 0x0401))
    alpn_body = b"\x02h2"
    alpn = _extension(0x0010, struct.pack("!H", len(alpn_body)) + alpn_body)
    supported_versions = _extension(0x002B, struct.pack("!BHH", 4, 0x0304, 0x0303))
    extensions = server_name + supported_groups + signature_algorithms + alpn + supported_versions

    ciphers = struct.pack("!HHHH", 0x1301, 0x1302, 0x1303, 0xC02F)
    body = (
        struct.pack("!H", 0x0303)
        + bytes(range(32))
        + b"\x00"  # no session id
        + struct.pack("!H", len(ciphers))
        + ciphers
        + b"\x01\x00"  # compression: null only
        + struct.pack("!H", len(extensions))
        + extensions
    )
    handshake = b"\x01" + len(body).to_bytes(3, "big") + body
    return b"\x16\x03\x01" + struct.pack("!H", len(handshake)) + handshake


def write_tls_capture(path: Path) -> None:
    """One TCP flow to port 443 carrying the ClientHello above, byte-deterministic."""
    hello = _client_hello()
    client_seq, server_seq = 2000, 7000
    steps = [
        (TLS_CLIENT, TLS_SERVER, TLS_SPORT, 443, client_seq, 0, CANARY.SYN, b""),
        (
            TLS_SERVER,
            TLS_CLIENT,
            443,
            TLS_SPORT,
            server_seq,
            client_seq + 1,
            CANARY.SYN | CANARY.ACK,
            b"",
        ),
        (TLS_CLIENT, TLS_SERVER, TLS_SPORT, 443, client_seq + 1, server_seq + 1, CANARY.ACK, b""),
        (
            TLS_CLIENT,
            TLS_SERVER,
            TLS_SPORT,
            443,
            client_seq + 1,
            server_seq + 1,
            CANARY.PSH | CANARY.ACK,
            hello,
        ),
        (
            TLS_SERVER,
            TLS_CLIENT,
            443,
            TLS_SPORT,
            server_seq + 1,
            client_seq + 1 + len(hello),
            CANARY.ACK,
            b"",
        ),
        (
            TLS_CLIENT,
            TLS_SERVER,
            TLS_SPORT,
            443,
            client_seq + 1 + len(hello),
            server_seq + 1,
            CANARY.FIN | CANARY.ACK,
            b"",
        ),
        (
            TLS_SERVER,
            TLS_CLIENT,
            443,
            TLS_SPORT,
            server_seq + 1,
            client_seq + 2 + len(hello),
            CANARY.FIN | CANARY.ACK,
            b"",
        ),
    ]

    packets = []
    for index, (src, dst, sport, dport, seq, ack, flags, payload) in enumerate(steps):
        segment = CANARY.tcp(sport, dport, seq, ack, flags, src, dst, payload)
        frame = CANARY.ethernet(CANARY.ipv4(src, dst, segment, ident=500 + index))
        packets.append((TLS_BASE_TS + index * 0.01, frame))
    CANARY.write_pcap(str(path), packets)


def rule_lines() -> dict[int, str]:
    """The synthetic rules, keyed by SID."""
    lines = {}
    for line in SYNTHETIC_RULES.read_text(encoding="utf-8").splitlines():
        if not line.startswith("alert"):
            continue
        match = re.search(r"\bsid:(\d+);", line)
        assert match is not None, f"synthetic rule has no sid: {line}"
        lines[int(match.group(1))] = line
    return lines


RULES = rule_lines()


def make_snapshot(
    root: Path,
    contents: Mapping[str, Sequence[int]],
    classes: Mapping[str, str] | None = None,
    *,
    raw: bool = True,
    extra_raw: Mapping[str, Sequence[int]] | None = None,
    snapshot_id: str | None = None,
) -> Path:
    """Hand-build the snapshot layout of spec §7 from `contents` (source name → SIDs).

    Stands in for step 4's ``write_snapshot`` so this step stays independently testable.
    ``raw=False`` omits the per-source rule files, which is how the "this snapshot cannot
    attribute its SIDs" failure is injected. ``extra_raw`` adds SIDs to a source's ``raw/``
    file *without* admitting them — which is what as-fetched text really looks like, since
    admission rejects most of it.

    `snapshot_id` defaults to the real ``sha256(rules.rules)[:16]`` that spec §7 defines, so
    fixtures are internally consistent the way a written snapshot is; pass a string to inject
    an id that does not match its own rules.
    """
    classes = classes or {}
    extra_raw = extra_raw or {}
    snapshot = root / "snapshot"
    snapshot.mkdir(parents=True, exist_ok=True)

    admissions = []
    admitted: list[str] = []
    for name in sorted(contents):
        lines = [RULES[sid] for sid in sorted(contents[name])]
        admitted.extend(lines)
        if raw:
            raw_path = snapshot / "raw" / f"{name}.rules"
            raw_path.parent.mkdir(parents=True, exist_ok=True)
            fetched = lines + [RULES[sid] for sid in sorted(extra_raw.get(name, ()))]
            # A comment line and a blank line, because raw text is "as fetched" and real
            # feeds ship both — the SID scan must skip them.
            raw_path.write_text(f"# {name} as fetched\n\n" + "\n".join(fetched) + "\n")
        admissions.append(
            SourceAdmission(
                name=name,
                url=f"https://example.invalid/{name}.rules",
                licence="MIT",
                source_class=classes.get(name, "signature"),
                admission_basis="wholesale",
                rules_fetched=len(lines),
                rules_admitted=len(lines),
                rules_excluded_no_confidence=0,
                rules_excluded_low_confidence=0,
                rules_excluded_low_severity=0,
                rules_excluded_commented=0,
                ja4_rules_admitted=sum("ja4.hash" in line for line in lines),
                ja3_rules_admitted=0,
                fetched_at="2026-08-12T00:00:00.000000Z",
            )
        )

    rules = snapshot / "rules.rules"
    rules.write_text("\n".join(admitted) + "\n" if admitted else "")
    manifest = SnapshotManifest(
        snapshot_id=snapshot_id or hashlib.sha256(rules.read_bytes()).hexdigest()[:16],
        created_at="2026-08-12T00:00:00.000000Z",
        flabel_version="0.0.0",
        sources=tuple(admissions),
        total_admitted=len(admitted),
        total_ja4_admitted=sum(admission.ja4_rules_admitted for admission in admissions),
    )
    (snapshot / "manifest.json").write_text(json.dumps(dataclasses.asdict(manifest), indent=2))
    return snapshot


def snapshot_id_of(snapshot: Path) -> str:
    """The id the manifest claims, read the way `provenance` will read it."""
    return json.loads((snapshot / "manifest.json").read_text())["snapshot_id"]


def reseal(snapshot: Path) -> None:
    """Recompute `snapshot_id` after a test has rewritten ``rules.rules``.

    Needed because the id is verified against the file's hash: without this, every test that
    injects a *rules* fault would trip the consistency check first and prove nothing about the
    fault it meant to inject.
    """
    document = json.loads((snapshot / "manifest.json").read_text())
    digest = hashlib.sha256((snapshot / "rules.rules").read_bytes()).hexdigest()
    document["snapshot_id"] = digest[:16]
    (snapshot / "manifest.json").write_text(json.dumps(document, indent=2))


