def test_an_unknown_manifest_field_is_tolerated(tmp_path):
    """Phase 2 must be additive (spec §2.7), so an unrecognised key is not fatal.

    The manifest is written by flabel, not by hand, so the `config.py` argument for rejecting
    unknown keys does not apply: rejecting them would mean a version that adds a field makes
    every snapshot already in `.flabel/rules/` unreadable.
    """
    snapshot = make_snapshot(tmp_path, {"et/open": [HTTP_SID]})
    document = json.loads((snapshot / "manifest.json").read_text())
    document["some_field_a_later_version_added"] = 7
    document["sources"][0]["another_one"] = "x"
    (snapshot / "manifest.json").write_text(json.dumps(document))

    manifest = suricata.load_manifest(snapshot)

    assert manifest.sources[0].name == "et/open"


