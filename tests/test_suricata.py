"""Suricata invocation and eve.json parsing (docs/spec.md §8, PLAN.md step 6).

Suricata is invoked for real here — the testing line is *tools real, network stubbed*
(spec §2), and a mock would encode our assumptions about the very tool behaviour that needs
verifying. Those tests carry ``@pytest.mark.requires_tools``. Nothing in this file makes a
network call or contacts a PANW device.

Two things are synthesized rather than sourced, both so the expected result is
*known-correct* rather than empirical:

* **the rules** — ``tests/fixtures/rules/synthetic.rules``, whose header explains why they
  avoid ``$HOME_NET``;
* **the snapshot** — a hand-built directory (``rules.rules`` + ``manifest.json`` +
  ``raw/<source>.rules``) rather than one written by ``rules/snapshot.py``, which lands in
  step 4 and is being built in parallel. That keeps this step independently testable, and
  the layout it builds is the one spec §7 documents.

The TLS capture for the JA4 test is generated into ``tmp_path`` rather than committed:
``tests/fixtures/`` has a deliberately narrow ``.gitignore`` exception, and a capture that
can be regenerated byte-for-byte does not need to live in git.
"""

