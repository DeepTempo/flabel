# --- snapshot validation -------------------------------------------------------------------
#
# All of these run before any subprocess, so they need no toolchain. A snapshot that cannot
# support provenance is a hard failure (spec §7, §11): every one of these conditions would
# otherwise produce a run that looks clean and labels nothing, which is indistinguishable
# from a capture that contained nothing.


def test_missing_snapshot_directory_is_a_hard_failure(tmp_path):
    with pytest.raises(SnapshotError):
        suricata.run_suricata(BENIGN, tmp_path / "nope", tmp_path / "out")


def test_missing_rules_file_is_a_hard_failure(tmp_path):
    snapshot = make_snapshot(tmp_path, {"et/open": [HTTP_SID]})
    (snapshot / "rules.rules").unlink()

    with pytest.raises(SnapshotError, match="rules.rules"):
        suricata.run_suricata(BENIGN, snapshot, tmp_path / "out")


def test_empty_rules_file_is_a_hard_failure(tmp_path):
    """Zero rules can never produce a label, and Suricata exits 0 having loaded none.

    Verified on 8.0.6: pointing ``-S`` at a missing or empty file is a *warning*, and the run
    completes successfully with an empty alert set. That is the most dangerous shape a bug
    can take here, so it is caught before the tool is invoked.
    """
    snapshot = make_snapshot(tmp_path, {"et/open": [HTTP_SID]})
    (snapshot / "rules.rules").write_text("# nothing admitted\n")
    reseal(snapshot)

    with pytest.raises(SnapshotError, match="no rules"):
        suricata.run_suricata(BENIGN, snapshot, tmp_path / "out")


