def test_raw_rules_for_a_source_absent_from_the_manifest_is_a_hard_failure(tmp_path):
    """The manifest is the authority on which sources are in a snapshot.

    A ``raw/`` file the manifest does not mention means the two disagree, and the manifest is
    where ``source_class`` — hence `may_label` — comes from.
    """
    snapshot = make_snapshot(tmp_path, {"et/open": [HTTP_SID]})
    (snapshot / "raw" / "mystery.rules").write_text(RULES[JA4_SID] + "\n")

    with pytest.raises(SnapshotError, match="mystery"):
        suricata.run_suricata(BENIGN, snapshot, tmp_path / "out")


def test_a_snapshot_id_that_does_not_hash_its_own_rules_is_a_hard_failure(tmp_path):
    """Spec §7 calls the id self-verifying, so it is actually verified.

    `snapshot_id` is read from `manifest.json` while the rules that fire come from
    `rules.rules`. Without this check, editing `rules.rules` leaves every label still claiming
    the original id — an origin that cannot be traced while looking perfectly traceable.
    """
    snapshot = make_snapshot(tmp_path, {"et/open": [HTTP_SID]}, snapshot_id=WRONG_SNAPSHOT_ID)

    with pytest.raises(SnapshotError, match="not internally consistent"):
        suricata.run_suricata(BENIGN, snapshot, tmp_path / "out")


